#!/usr/bin/env node
// Compiles packages/fixtures/contracts/*.sol with the npm `solc` (solc-js) package and writes
// src/artifacts.generated.ts (ABI `as const` + creation bytecode). The output is checked in so
// consumers never need a compiler; a unit test recompiles and asserts the file is up to date.
//
//   node packages/fixtures/scripts/compile-contracts.mjs          # regenerate
//   node packages/fixtures/scripts/compile-contracts.mjs --check  # exit 1 if stale
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const here = dirname(fileURLToPath(import.meta.url));
export const PKG_DIR = join(here, "..");
export const CONTRACTS_DIR = join(PKG_DIR, "contracts");
export const OUT_FILE = join(PKG_DIR, "src", "artifacts.generated.ts");

/** Contracts exported to TypeScript (others in the sources are internal). */
export const EXPORTED = ["FixtureERC721A", "Fixture1155", "FixtureFixedPriceMinter", "BondingCurveLaunchpad", "LaunchToken"];

/** @returns {string} the generated TypeScript module source */
export function compileFixtures() {
  const solc = require("solc");
  const sources = {};
  for (const f of readdirSync(CONTRACTS_DIR).filter((f) => f.endsWith(".sol")).sort()) {
    sources[f] = { content: readFileSync(join(CONTRACTS_DIR, f), "utf8").replace(/\r\n/g, "\n") };
  }
  const input = {
    language: "Solidity",
    sources,
    settings: {
      // "paris" avoids PUSH0/MCOPY so artifacts also run on older local nodes.
      evmVersion: "paris",
      optimizer: { enabled: true, runs: 200 },
      metadata: { bytecodeHash: "none" },
      outputSelection: { "*": { "*": ["abi", "evm.bytecode.object"] } },
    },
  };
  const output = JSON.parse(solc.compile(JSON.stringify(input)));
  const errors = (output.errors ?? []).filter((e) => e.severity === "error");
  if (errors.length) throw new Error(errors.map((e) => e.formattedMessage).join("\n"));

  const found = {};
  for (const file of Object.keys(output.contracts ?? {})) {
    for (const [name, c] of Object.entries(output.contracts[file])) found[name] = c;
  }
  let ts = `// GENERATED by scripts/compile-contracts.mjs with solc ${solc.version()} - do not edit.\n`;
  ts += `// Run \`npm run compile:contracts -w @mint-engine/fixtures\` after changing contracts/*.sol.\n\n`;
  ts += `export const SOLC_VERSION = ${JSON.stringify(solc.version())};\n\n`;
  for (const name of EXPORTED) {
    const c = found[name];
    if (!c) throw new Error(`contract ${name} not found in compiler output`);
    ts += `export const ${name} = {\n  abi: ${JSON.stringify(c.abi)},\n  bytecode: "0x${c.evm.bytecode.object}",\n} as const;\n\n`;
  }
  return ts;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  const ts = compileFixtures();
  if (process.argv.includes("--check")) {
    const current = readFileSync(OUT_FILE, "utf8").replace(/\r\n/g, "\n");
    if (current !== ts) {
      console.error("artifacts.generated.ts is stale; run npm run compile:contracts -w @mint-engine/fixtures");
      process.exit(1);
    }
    console.log("artifacts up to date");
  } else {
    writeFileSync(OUT_FILE, ts);
    console.log(`wrote ${OUT_FILE}`);
  }
}
