// Throwaway local wallets for tests. Written to <repo>/fixtures/.local-wallets.json (gitignored).
import { chmodSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { assertLocalRpc } from "./env.js";
import { fileURLToPath } from "node:url";
import { parseEther, type Address, type Hex } from "viem";
import { generatePrivateKey, privateKeyToAccount } from "viem/accounts";
import { setEvmBalance } from "./evm.js";
import { airdropAndConfirm, generateSolanaKeypair, type SolanaKeypair } from "./solana/rpc.js";

/**
 * Default path: <repo root>/fixtures/.local-wallets.json, matching the root .gitignore entry. Resolved relative to
 * this module (works from packages/fixtures/src and /dist, incl. the workspace symlink). If the package was installed
 * as a real copy under node_modules, fall back to <cwd>/fixtures/.local-wallets.json so keys never land in node_modules.
 */
export const DEFAULT_LOCAL_WALLETS_PATH = (() => {
  const p = fileURLToPath(new URL("../../../fixtures/.local-wallets.json", import.meta.url));
  return /[\\/]node_modules[\\/]/.test(p) ? join(process.cwd(), "fixtures", ".local-wallets.json") : p;
})();

export interface LocalWallet {
  index: number;
  evm: { address: Address; privateKey: Hex };
  solana: SolanaKeypair;
}

export interface LocalWalletsFile {
  warning: string;
  createdAt: string;
  wallets: LocalWallet[];
  funded: { evm: string[]; solana: string | null };
}

export interface FundOptions {
  /** Output file; defaults to DEFAULT_LOCAL_WALLETS_PATH. */
  path?: string;
  /** Local anvil RPCs to fund via anvil_setBalance. Omit to skip EVM funding. */
  evmRpcUrls?: string[];
  evmBalanceWei?: bigint;
  /** Local solana-test-validator RPC to airdrop on. Omit to skip Solana funding. */
  solanaRpcUrl?: string;
  solanaLamports?: bigint;
}

/**
 * Generate `n` fresh throwaway wallets (EVM + Solana), optionally fund them on local chains,
 * and write them to the gitignored wallets file. Never use these keys anywhere but local chains.
 */
export async function fundLocalWallets(n: number, opts: FundOptions = {}): Promise<LocalWalletsFile & { path: string }> {
  if (!Number.isInteger(n) || n < 1 || n > 100) throw new Error(`fundLocalWallets: n must be 1..100, got ${n}`);
  const wallets: LocalWallet[] = Array.from({ length: n }, (_, index) => {
    const privateKey = generatePrivateKey();
    return { index, evm: { address: privateKeyToAccount(privateKey).address, privateKey }, solana: generateSolanaKeypair() };
  });

  const evmRpcUrls = opts.evmRpcUrls ?? [];
  // Validate every URL before generating side effects anywhere.
  for (const url of evmRpcUrls) assertLocalRpc(url);
  if (opts.solanaRpcUrl) assertLocalRpc(opts.solanaRpcUrl);

  const path = opts.path ?? DEFAULT_LOCAL_WALLETS_PATH;
  const file: LocalWalletsFile = {
    warning: "THROWAWAY LOCAL TEST KEYS - never fund on a public network. Generated by @mint-engine/fixtures. Overwritten on each fundLocalWallets() call.",
    createdAt: new Date().toISOString(),
    wallets,
    funded: { evm: [], solana: null },
  };
  const save = () => {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, JSON.stringify(file, null, 2) + "\n", { mode: 0o600 });
    chmodSync(path, 0o600); // writeFileSync's mode only applies on create
  };
  // Persist keys BEFORE funding so a partial failure never strands funded-but-unsaved wallets.
  save();

  const evmWei = opts.evmBalanceWei ?? parseEther("100");
  for (const url of evmRpcUrls) {
    await Promise.all(wallets.map((w) => setEvmBalance(url, w.evm.address, evmWei)));
    file.funded.evm.push(url);
    save();
  }
  if (opts.solanaRpcUrl) {
    const lamports = opts.solanaLamports ?? 10_000_000_000n; // 10 SOL
    const rpc = opts.solanaRpcUrl;
    // The local faucet rate-limits bursts; airdrop sequentially.
    for (const w of wallets) await airdropAndConfirm(rpc, w.solana.publicKey, lamports);
    file.funded.solana = rpc;
    save();
  }
  return { ...file, path };
}
